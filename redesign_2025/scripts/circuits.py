LINEAR = {'vb1', 'k', 'vc'}


def make(name, x, **kw):
    if name == 'rgc': return rgc(x, **kw)
    if name == 'mdfrgc': return mdfrgc(x, **kw)
    if name == 'mdfrgc_t': return mdfrgc_t(x, **kw)
    if name.startswith('shaaban_'): return shaaban(x, peak=name.split('_')[1], **kw)
    if name == 'pf_tia': return pf_tia(x, **kw)
    if name == 'cm_nrc_d1': return cm_nrc(x, tap='d1', **kw)
    if name == 'cm_nrc_out': return cm_nrc(x, tap='out', **kw)
    if name == 'cm_rgc': return cm_nrc(dict(x, w3=0), **kw)
    raise KeyError(name)
