"""All circuits of the 2025 redesign study, as parameterised element lists.

Every circuit runs at VDD = 1 V with the photodiode modelled as Iin (ac 1 A into node
'in') plus Cpd at 'in', and a load CL at 'out'.  Bias currents come from an ideal
reference current into a diode-connected device (counted in the supply current).
Lengths >= 100 nm everywhere so the same sizes port to gpdk090 (Lmin = 100 nm).

x = dict of design variables (widths in um, R in ohm, C in F, L in H, currents in A).
"""
LMIN = 100          # nm, gpdk090 minimum


def common(x, cpd, cl):
    return [('V', 'Vdd', 'vdd', '0', 1.0),
            ('C', 'Cpd', 'in', '0', cpd),
            ('C', 'CL', 'out', '0', cl),
            ('I', 'Iin', '0', 'in', 0, 1)]


def nbias(x, name='vbn', iref=20e-6, wd=1.0, l=200):
    """NMOS bias line: Iref into diode Mdn (W = wd um).  A sink of width W carries iref*W/wd."""
    return [('I', 'Ibn', 'vdd', name, iref, None),
            ('M', 'Mdn', name, name, '0', '0', 'n', wd, l),
            ('C', 'Cbn', name, '0', 2e-12)]


def pbias(x, name='vbp', iref=20e-6, wd=2.0, l=200):
    return [('I', 'Ibp', name, '0', iref, None),
            ('M', 'Mdp', name, name, 'vdd', 'vdd', 'p', wd, l),
            ('C', 'Cbp', name, 'vdd', 2e-12)]


# --------------------------------------------------------------------------------------
# 1. Conventional RGC (Park & Yoo 2004 style) - the reference topology of the base paper
# --------------------------------------------------------------------------------------
def rgc(x, cpd=0.45e-12, cl=50e-15):
    return common(x, cpd, cl) + nbias(x) + [
        ('M', 'Mb', 'in', 'vbn', '0', '0', 'n', x['wb'], 200),       # input bias sink (Rb)
        ('M', 'M1', 'out', 'x', 'in', '0', 'n', x['w1'], LMIN),      # common-gate input
        ('R', 'R1', 'vdd', 'out', x['r1']),                          # load
        ('M', 'M2', 'x', 'in', '0', '0', 'n', x['w2'], LMIN),        # booster (A1)
        ('R', 'R2', 'vdd', 'x', x['r2']),
    ]


# --------------------------------------------------------------------------------------
# 2. BASE PAPER: Abdollahi et al., IEEE Access 13 (2025) - modified dual-feedback RGC with
#    an intrinsic negative-RC network.  Reconstructed from the paper's Eqs. (4)-(11):
#    the RGC above plus a second CS amplifier A2 (M3, source degenerated by R3 || C3) whose
#    gate is the output and whose drain shares the booster load R2 at node x.
# --------------------------------------------------------------------------------------
def mdfrgc(x, cpd=0.45e-12, cl=50e-15):
    return rgc(x, cpd, cl) + [
        ('M', 'M3', 'x', 'out', 's3', '0', 'n', x['w3'], LMIN),      # A2
        ('R', 'R3', 's3', '0', x['r3']),
        ('C', 'C3', 's3', '0', x['c3']),
    ]


# --------------------------------------------------------------------------------------
# 2b. NEW: voltage-trimmable negative-RC network.  The degeneration resistor R3 of the base
#     paper is replaced by an NMOS in triode (Mr3, gate = control voltage vc) in parallel with
#     a fixed R3, so one control voltage moves the zero/pole pair of A2 (and with it the
#     bandwidth and peaking) after fabrication.  vc = 0 leaves the base-paper circuit.
# --------------------------------------------------------------------------------------
def mdfrgc_t(x, cpd=0.45e-12, cl=50e-15):
    return rgc(x, cpd, cl) + [
        ('M', 'M3', 'x', 'out', 's3', '0', 'n', x['w3'], LMIN),
        ('R', 'R3', 's3', '0', x['r3']),
        ('C', 'C3', 's3', '0', x['c3']),
        ('M', 'Mr3', 's3', 'vc', '0', '0', 'n', x['wr3'], LMIN),
        ('V', 'Vc', 'vc', '0', x['vc']),
    ]


# --------------------------------------------------------------------------------------
# 3. Shaaban et al., IJCTA 53 (2025) - current-mirror TIA with feedback + shunt peaking.
#    Full text unavailable: reconstructed from the abstract and figure captions only
#    (diode-connected input, mirror with gain, shunt feedback Rf, peaking at the load).
#    peak = 'L' passive inductor, 'AN' NMOS (source-follower) active inductor,
#    'AP' PMOS (diode + gate resistor) active inductor.
# --------------------------------------------------------------------------------------
def shaaban(x, cpd=0.45e-12, cl=50e-15, peak='L'):
    el = common(x, cpd, cl) + pbias(x) + [
        ('M', 'Mp1', 'in', 'vbp', 'vdd', 'vdd', 'p', x['wp1'], 200),  # input bias source
        ('M', 'M1', 'in', 'in', '0', '0', 'n', x['w1'], LMIN),        # diode input
        ('M', 'M2', 'out', 'in', '0', '0', 'n', x['w2'], LMIN),       # mirror, gain W2/W1
        ('R', 'Rf', 'out', 'in', x['rf']),                            # shunt feedback
    ]
    if peak == 'L':
        el += [('R', 'RL', 'vdd', 'lx', x['rl']), ('L', 'Lp', 'lx', 'out', x['lp'])]
    elif peak == 'AN':
        el += [('M', 'Ma', 'vdd', 'ga', 'out', '0', 'n', x['wa'], LMIN),
               ('R', 'Rg', 'vdd', 'ga', x['rg'])]
    elif peak == 'AP':
        el += [('M', 'Ma', 'out', 'ga', 'vdd', 'vdd', 'p', x['wa'], LMIN),
               ('R', 'Rg', 'ga', 'out', x['rg']),
               ('R', 'RL', 'vdd', 'out', x['rl'])]
    return el


# --------------------------------------------------------------------------------------
# 4. Earlier work of this project: FVF input + current mirror + source-follower feedback
#    ("PF-TIA", repo paper_conecct).  Same bias style as the other circuits here.
# --------------------------------------------------------------------------------------
def pf_tia(x, cpd=0.45e-12, cl=50e-15):
    return common(x, cpd, cl) + pbias(x) + [
        ('V', 'Vb1', 'vb1', '0', x['vb1']),
        ('R', 'Rn', 'vdd', 'n', x['rn']),
        ('M', 'M1', 'n', 'vb1', 'in', '0', 'n', x['w1'], LMIN),
        ('M', 'M2', 'in', 'n', '0', '0', 'n', x['w2'], LMIN),
        ('M', 'M3', 'out', 'n', '0', '0', 'n', x['w3'], LMIN),
        ('M', 'M3b', 'out', 'vbp', 'vdd', 'vdd', 'p', x['w3b'], 200),
        ('M', 'Mf', 'vdd', 'out', 'in', '0', 'n', x['wf'], LMIN),
    ]


# --------------------------------------------------------------------------------------
# 5. PROPOSED: current-mirror RGC with an intrinsic negative-RC cross path (CM-NRC-RGC).
#    RGC input (M1, M2, Mb) -> the M1 drain current is mirrored by Mp1/Mp2 (gain K) into
#    the output load RL, so the high-impedance output node is decoupled from the
#    common-gate drain (1/gm_p1).  The cross path M3 (degenerated by R3 || C3) is driven
#    from the mirror node d1 (variant 'd1', regenerative like the base paper) or from the
#    output (variant 'out', degenerative global feedback).
# --------------------------------------------------------------------------------------
def cm_nrc(x, cpd=0.45e-12, cl=50e-15, tap='d1'):
    el = common(x, cpd, cl) + nbias(x) + [
        ('M', 'Mb', 'in', 'vbn', '0', '0', 'n', x['wb'], 200),
        ('M', 'M1', 'd1', 'x', 'in', '0', 'n', x['w1'], LMIN),
        ('M', 'M2', 'x', 'in', '0', '0', 'n', x['w2'], LMIN),
        ('R', 'R2', 'vdd', 'x', x['r2']),
        ('M', 'Mp1', 'd1', 'd1', 'vdd', 'vdd', 'p', x['wp1'], LMIN),
        ('M', 'Mp2', 'out', 'd1', 'vdd', 'vdd', 'p', x['wp1'] * x['k'], LMIN),
        ('R', 'RL', 'out', '0', x['rl']),
    ]
    if x.get('w3', 0) > 0.11:
        el += [('M', 'M3', 'x', tap, 's3', '0', 'n', x['w3'], LMIN),
               ('R', 'R3', 's3', '0', x['r3']),
               ('C', 'C3', 's3', '0', x['c3'])]
    return el


