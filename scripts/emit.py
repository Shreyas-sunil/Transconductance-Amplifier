def asc_items(circ):
    """Return list of (symbol, x, y, name, value, value2, {pin: net})."""
    el, P = get(circ)
    items = []
    for e in el:
        k, name = e[0], e[1]
        x, y = PLACE[circ][name]
        if k == 'M':
            _, _, d, g, s, b, typ, w, l = e
            ad, pd = C.mos_geom(w)
            items.append(('tia_nmos4' if typ == 'n' else 'tia_pmos4', x, y, name, 'nmos90' if typ == 'n' else 'pmos90',
                          f'l={l:g}n w={w:g}u ad={ad:g}p as={ad:g}p pd={pd:g}u ps={pd:g}u',
                          {'D': d, 'G': g, 'S': s, 'B': b}))
        elif k in 'RLC':
            sym = {'R': 'res', 'L': 'ind', 'C': 'cap'}[k]
            items.append((sym, x, y, name, e[4], None, {'A': e[2], 'B': e[3]}))
        elif k == 'V':
            items.append(('voltage', x, y, name, e[4], None, {'+': e[2], '-': e[3]}))
        elif k == 'I':
            val = e[4] + (f' AC {e[5]}' if e[5] else '')
            items.append(('current', x, y, name, val, None, {'+': e[2], '-': e[3]}))
    return items, P


def ltspice_asc(circ):
    items, P = asc_items(circ)
    L = ['Version 4', 'SHEET 1 2200 1200']
    wires, flags, syms = [], [], []
    for sym, x, y, name, val, val2, pins in items:
        for pn, net in pins.items():
            dx, dy, sx, sy = PINS[sym][pn]
            x1, y1 = x + dx, y + dy
            wires.append(f'WIRE {x1} {y1} {x1 + sx} {y1 + sy}')
            flags.append(f'FLAG {x1 + sx} {y1 + sy} {net}')
        syms.append(f'SYMBOL {sym} {x} {y} R0')
        syms.append(f'SYMATTR InstName {name}')
        syms.append(f'SYMATTR Value {val}')
        if val2:
            syms.append(f'SYMATTR Value2 {val2}')
    L += wires + flags + syms
    ty = 720
    for t in [f'!.include ptm90.lib', '!' + C.param_line(P), f"!.temp {P['temp']}", '!.ac dec 40 10Meg 200G',
              ';.noise V(out) Iin dec 40 10Meg 200G', '!.meas AC zt0 FIND mag(V(out)) AT 100Meg',
              '!.meas AC f3db WHEN mag(V(out))=zt0/sqrt(2) FALL=1'] + \
             ([';.step param vtune 0 0.32 0.04'] if circ == 'prop' else []) + \
             ([';.step param idc list 0 100u 300u 500u'] if circ == 'dcc' else []) + \
             [f';{TITLE[circ]}', ';Nets are joined by label (same name = same net). Transimpedance = V(out) for the 1 A AC source Iin.']:
        L.append(f'TEXT -720 {ty} Left 2 {t}'); ty += 32
    open(os.path.join(NL, 'ltspice', FNAME[circ] + '.asc'), 'w').write('\n'.join(L) + '\n')
    return items


def asc_netlist_check(circ):
    """Re-derive connectivity from the .asc geometry and compare with the intended netlist."""
    path = os.path.join(NL, 'ltspice', FNAME[circ] + '.asc')
    wires, flags, syms = [], {}, []
    cur = None
    for ln in open(path):
        t = ln.split()
        if t[0] == 'WIRE': wires.append(tuple(map(int, t[1:5])))
        elif t[0] == 'FLAG': flags[(int(t[1]), int(t[2]))] = t[3]
        elif t[0] == 'SYMBOL': cur = [t[1], int(t[2]), int(t[3]), None]; syms.append(cur)
        elif t[0] == 'SYMATTR' and t[1] == 'InstName': cur[3] = t[2]
    got = {}
    for sym, x, y, name in syms:
        got[name] = {}
        for pn, (dx, dy, sx, sy) in PINS[sym].items():
            p = (x + dx, y + dy)
            ends = [w[2:] for w in wires if w[:2] == p] + [w[:2] for w in wires if w[2:] == p]
            nets = {flags[e] for e in ends if e in flags}
            assert len(nets) == 1, (name, pn, nets)
            got[name][pn] = nets.pop()
    want = {i[3]: i[6] for i in asc_items(circ)[0]}
    assert got == want, 'ASC connectivity mismatch'
    # no two different nets share a point
    pts = {}
    for (x1, y1, x2, y2) in wires:
        for p in ((x1, y1), (x2, y2)):
            pts.setdefault(p, 0); pts[p] += 1
    assert all(v == 1 for v in pts.values()), 'overlapping wire ends'
    return True


# ----------------------------------------------------------------------------- Spectre
def spectre(circ):
    el, P = get(circ)
    par = ' '.join(f'{k}={v}' for k, v in P.items() if k != 'temp')
    L = [f'// {TITLE[circ]}', f'// Run:  spectre {FNAME[circ]}.scs      (results in {FNAME[circ]}.raw, open with ViVA)',
         '// Generated by scripts/emit.py', 'simulator lang=spectre', 'global 0',
         'include "ptm90.lib"   // SPICE-syntax PTM card; Spectre reads non-.scs includes as SPICE',
         f'parameters {par}', '']
    for e in el:
        k, name = e[0], e[1]
        if k == 'M':
            _, _, d, g, s, b, typ, w, l = e
            ad, pd = C.mos_geom(w)
            L.append(f"{name} ({d} {g} {s} {b}) {'nmos90' if typ == 'n' else 'pmos90'} w={w:g}u l={l:g}n "
                     f"as={ad:g}p ad={ad:g}p ps={pd:g}u pd={pd:g}u")
        elif k == 'R': L.append(f"{name} ({e[2]} {e[3]}) resistor r={e[4].strip('{}')}")
        elif k == 'C': L.append(f"{name} ({e[2]} {e[3]}) capacitor c={e[4].strip('{}')}")
        elif k == 'L': L.append(f"{name} ({e[2]} {e[3]}) inductor l={e[4].strip('{}')}")
        elif k == 'V': L.append(f"{name} ({e[2]} {e[3]}) vsource dc={e[4].strip('{}')} type=dc")
        elif k == 'I': L.append(f"{name} ({e[2]} {e[3]}) isource dc={e[4].strip('{}')} type=dc" + (f" mag={e[5]}" if e[5] else ''))
    L += ['', f"simOpts options temp={P['temp']} tnom=27 reltol=1e-4 vabstol=1e-6 iabstol=1e-12 save=allpub",
          'dcOp dc oppoint=logfile', 'dcOpInfo info what=oppoint where=rawfile',
          'acZt ac start=10M stop=200G dec=40',
          'noiseIn (out 0) noise start=10M stop=200G dec=40 iprobe=Iin']
    if circ == 'prop':
        L += ['// bandwidth tuning sweep', 'swVt sweep param=vtune start=0 stop=0.32 step=0.04 {',
              '    acTune ac start=10M stop=200G dec=40', '}']
    if circ == 'dcc':
        L += ['// average-photocurrent sweep: the DC-cancellation loop holds the bandwidth',
              'swIdc sweep param=idc values=[0 100u 300u 500u] {', '    acIdc ac start=1k stop=200G dec=20', '}',
              '// photocurrent step 0 -> 200 uA -> 0 on top of idc: settling of the cancellation loop',
              'Istep (0 in) isource type=pwl wave=[0 0 1u 0 1.001u 200u 6u 200u 6.001u 0]',
              'tranStep tran stop=11u maxstep=2n']
    open(os.path.join(NL, 'cadence', FNAME[circ] + '.scs'), 'w').write('\n'.join(L) + '\n')


